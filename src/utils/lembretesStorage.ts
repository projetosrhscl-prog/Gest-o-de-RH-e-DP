      title: `📊 Fechamento da Folha de Pagamento (${monthStr}/${currentYear})`,
      description: `Dia 25: Prazo limite para conferência de ponto, envio de eventos, adicionais e apuração proporcional para a contabilidade.`,
      date: `${currentYear}-${monthStr}-25`,
      category: 'FOLHA_DP',
      priority: 'URGENTE',
