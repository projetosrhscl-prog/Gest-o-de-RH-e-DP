      priority: 'MEDIA',
      status: 'PENDENTE',
      isAutoGenerated: true,
      sourceType: 'ADIANTAMENTO',
      recurrence: 'MENSAL',
      alertDaysBefore: 2,
      actionLabel: 'Ver DP & Benefícios',
